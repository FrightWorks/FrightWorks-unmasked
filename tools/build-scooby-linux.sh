#!/usr/bin/env bash
# Native Linux (x86_64) build of FrightWorks: UnMasked: portable tools -> logic overlay -> translate -> configure ->
# compile -> stage Play/. The Linux counterpart of tools/build-scooby.ps1 (adapted from FrightWorks-no100f's
# tools/build-no100f-linux.sh). Needs clang, ninja, python3 and curl on PATH; CMake and the .NET 10 SDK are downloaded
# into toolchain/ (nothing system-wide).
#   tools/build-scooby-linux.sh [path/to/game.iso|.ciso]
# FRIGHTWORKS_JOBS=<n> limits the parallel jobs (default: all cores). LOGIC_LEVELS=MAINMENU,W1L1 translates only those
# levels' logic modules (test builds; a playable build needs all).
# The disc image is only needed the first time (it is extracted to Disc/DATA). The game ends up in
# "Play/Scooby-Doo Re-Masked", with settings, saves and logs in Play/UserData (Play/portable.txt is the marker).
# There is no Linux launcher yet: run the game directly.
set -euo pipefail

root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
wc="$root/wiicompiled"
toolchain="$root/toolchain"
logs="$root/build-logs"
build="$wc/native-build-linux"
play="$root/Play"
exe_name="Scooby-Doo Re-Masked"
jobs="${FRIGHTWORKS_JOBS:-$(nproc)}"  # FRIGHTWORKS_JOBS caps the parallel jobs (the translator and the compiler)
logic_levels="${LOGIC_LEVELS:-all}"
mkdir -p "$logs"

status() { printf '%s %s\n' "$(date +%T)" "$*" | tee -a "$logs/status-linux.txt"; }
step() {  # step <name> <command...>: runs it with output in build-logs/<name>.log, stops on failure
    local name="$1"; shift
    status "$name: started"
    if ! "$@" >"$logs/$name.log" 2>&1; then
        status "$name: FAILED, see $logs/$name.log"
        tail -n 40 "$logs/$name.log"
        exit 1
    fi
    status "$name: ok"
}

# 0. The disc: Disc/DATA (sys/ + files/) and game/main.dol, the translation input.
if [[ ! -f "$root/Disc/DATA/sys/boot.bin" ]]; then
    [[ $# -ge 1 ]] || { echo "First build: pass your Scooby-Doo! Unmasked (USA, G5DE78) disc image (.iso/.gcm/.ciso)." >&2; exit 1; }
    step extract python3 "$root/tools/gc_extract.py" "$1" "$root/Disc/DATA"
fi
mkdir -p "$root/game"
[[ -f "$root/game/main.dol" ]] || cp "$root/Disc/DATA/sys/main.dol" "$root/game/main.dol"

# 1. Portable CMake and .NET 10 SDK
if [[ ! -x "$toolchain/CMake/bin/cmake" ]]; then
    status 'tools: downloading CMake 4.3.3'
    mkdir -p "$toolchain"
    curl -fsSL https://github.com/Kitware/CMake/releases/download/v4.3.3/cmake-4.3.3-linux-x86_64.tar.gz |
        tar -xz -C "$toolchain"
    mv "$toolchain/cmake-4.3.3-linux-x86_64" "$toolchain/CMake"
fi
# The .NET 10 SDK: tools/get-dotnet.py (also what tools/get-dotnet.ps1 runs on Windows) installs it into toolchain/dotnet
# and prints the path of dotnet as its last line.
step get-dotnet python3 "$root/tools/get-dotnet.py"
cmake="$toolchain/CMake/bin/cmake"
dotnet="$(tail -n 1 "$logs/get-dotnet.log")"
export DOTNET_ROLL_FORWARD=Major DOTNET_CLI_TELEMETRY_OPTOUT=1

# 2. Logic overlay and translate
cd "$wc"
project=projects/scooby/recomp.yml
sp=projects/scooby
translator=translator/src/Translator.Cli/bin/Release/net10.0/Translator.Cli.dll
# Every time: an existing DLL would otherwise keep translating with the old translator after translator changes.
step translator-build "$dotnet" build translator/src/Translator.Cli -c Release
# Logic modules: pre-relocated into game/main_logic.dol (text section 2 at 0x81800000), their functions appended to the
# function map (see projects/scooby/tools/build_logic_overlay.py).
overlay_args=("$sp/tools/build_logic_overlay.py" "$root/Disc/DATA/files" "$root/game/main.dol" "$root/game/main_logic.dol"
    "$sp/MAP_logic.txt" runtime/src/hle/scooby_logic_table.inc)
[[ "$logic_levels" == all ]] || overlay_args+=(--levels "$logic_levels")
step logic-overlay python3 -I "${overlay_args[@]}"
# main_logic.dol changes with the overlay; keep the manifest's sha256 pin and the loader's hash in step with it (each
# written only when it changed: both files are tracked).
sha="$(sha256sum "$root/game/main_logic.dol" | cut -d' ' -f1)"
python3 -I - "$sp/recomp.yml" "$sha" <<'EOF'
import re, sys
path, sha = sys.argv[1], sys.argv[2]
text = open(path, encoding='utf-8', newline='').read()
new = re.sub(r'(path: \.\./game/main_logic\.dol[^\n]*\n\s*sha256: )[0-9a-f]{64}', lambda m: m.group(1) + sha, text)
if new != text:
    open(path, 'w', encoding='utf-8', newline='').write(new)
EOF
sha_inc=runtime/src/hle/scooby_logic_dol_sha256.inc
sha_text="// AUTO-GENERATED by tools/build-scooby.ps1: SHA-256 of the game/main_logic.dol the translation was built from.
constexpr char kLogicDolSha256[] = \"$sha\";"
[[ "$(tr -d '\r' <"$sha_inc" 2>/dev/null)" == "$sha_text" ]] || printf '%s\n' "$sha_text" >"$sha_inc"
cat "$sp/MAP.txt" "$sp/MAP_logic.txt" >"$sp/MAP_all.txt"
step translate "$dotnet" "$translator" translate-recursive 0x80011C1C --project "$project" \
    --outdir generated/functions --output-metadata generated/base_translation_output.json \
    --production-source-bundle generated/base_translation_sources.bin \
    --no-function-files --prune-stale --threads "$jobs"
step data-init "$dotnet" "$translator" generate-data-init --project "$project"
step shards "$dotnet" "$translator" emit-build-shards --project "$project" \
    --base-metadata generated/base_translation_output.json --base-functions-dir generated/functions \
    --native-source-dir runtime/src --out generated/build_shards

# 3. Configure and compile (pinned dependencies, including the Linux Dawn package, are fetched by CMake)
step configure-linux "$cmake" -S runtime -B "$build" -G Ninja \
    -DCMAKE_C_COMPILER=clang -DCMAKE_CXX_COMPILER=clang++ \
    -DCMAKE_BUILD_TYPE=Release -DCMAKE_SYSTEM_PROCESSOR=x86_64 \
    -DAURORA_DAWN_PROVIDER=package -DAURORA_SDL3_PROVIDER=vendor -DCMAKE_POLICY_DEFAULT_CMP0168=NEW \
    -DRECOMP_TRANSLATED_COMPILE_JOBS="$jobs" -DRECOMP_GIT_EXECUTABLE="$(command -v git || true)"
step compile-linux "$cmake" --build "$build" --target WiiCompiled --parallel "$jobs"

# 4. Stage Play/: the program, its runtime files and a Config.toml pointing at Disc/DATA
pkill -f "^$play/$exe_name" 2>/dev/null || true
install -m 755 "$build/WiiCompiled" "$play/$exe_name"
for f in dsp_coef.bin cacert.pem initial_pipeline_cache.db; do
    [[ -f "$build/$f" ]] && cp "$build/$f" "$play/"
done
mkdir -p "$play/UserData"
[[ -f "$play/UserData/Config.toml" ]] || printf "[paths]\ndvd_root = '../../Disc/DATA'\n" >"$play/UserData/Config.toml"
status "DONE: run \"$play/$exe_name\""
